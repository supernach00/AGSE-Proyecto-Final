/* Genera HALF frames (L,R) corriendo el DDS de los 2 canales */
static void fill(int16_t *dst)
{
    for (int i = 0; i < HALF; i++) {
        acc[0] += ftw[0];
        acc[1] += ftw[1];
        int32_t c0 = (int32_t)sine_table[acc[0] >> 19] - 2048;  // centrar en 0
        int32_t c1 = (int32_t)sine_table[acc[1] >> 19] - 2048;
        int32_t l = salida_on[0] ? (c0 * amp[0]) / 2048 : 0;    // -2048..2047
        int32_t r = salida_on[1] ? (c1 * amp[1]) / 2048 : 0;
        dst[2*i]     = (int16_t)(l << 4);   // canal L (escala 12→16 bit con signo)
        dst[2*i + 1] = (int16_t)(r << 4);   // canal R
    }
}

